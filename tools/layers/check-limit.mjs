import assert from 'node:assert/strict';
import {densityLimitEvidence, isDensityLimit} from './limit.mjs';

const matrix = scale => [scale, 0, 0, scale, 0, 0];
const texture = (rasterScale = 2) => ({texture: 'texture.png', rect: [0, 0, 10, 10], rasterScale});
const layer = (node, children = [], extra = {}) => ({node, matrix: matrix(1), opacity: 1, rasterScale: 2, rect: [0, 0, 10, 10], children, ...extra});
const bundle = (root, tracks = []) => ({root, times: [0, 7, 40], tracks, textureScale: 2});
const transform = (node, scales) => ({node, property: 'transform', values: scales.map(matrix)});
const evidence = densityLimitEvidence(bundle(layer(0, [layer(1, [texture()])]), [transform(0, [1, 1.2, 1.4]), transform(1, [1, 1, 1])]), 23.5, 2);
assert.equal(evidence.enlarged, true);
assert.equal(evidence.layers[0].node, 1);
assert.ok(Math.abs(evidence.layers[0].scale - 1.3) < 1e-10);
assert.equal(evidence.layers[0].rasterScale, 2);
assert.equal(densityLimitEvidence(bundle(layer(0, [texture()]), [transform(0, [1, 1.3, 1.3])]), 40, 1).enlarged, false);
assert.equal(densityLimitEvidence(bundle(layer(0, [texture()], {matrix: matrix(1.3)})), 0, 2).enlarged, true);
assert.equal(densityLimitEvidence(bundle(layer(0, [texture()], {matrix: matrix(1.3)}), [transform(0, [1, 1, 1])]), 7, 2).enlarged, false);
assert.equal(densityLimitEvidence(bundle(layer(0, [], {matrix: matrix(4)})), 0, 2).enlarged, false);
assert.equal(densityLimitEvidence(bundle(layer(0, [], {matrix: matrix(4), clips: {file: 'mask.png', rect: [0, 0, 10, 10], rasterScale: 2}})), 0, 2).enlarged, false);
assert.equal(densityLimitEvidence(bundle(layer(0, [texture()], {matrix: matrix(4), opacity: 0})), 0, 2).enlarged, false);
const fading = bundle(layer(0, [layer(1, [texture()], {matrix: matrix(4)})]), [{node: 0, property: 'opacity', values: [1, 0, 1]}]);
assert.equal(densityLimitEvidence(fading, 7, 2).enlarged, false);
assert.equal(densityLimitEvidence(fading, 40, 2).enlarged, true);
const appearing = bundle(layer(0, [texture()], {matrix: matrix(1.3), opacity: 0}), [{node: 0, property: 'opacity', values: [0, 1, 1]}]);
assert.equal(densityLimitEvidence(appearing, 7, 2).enlarged, true);
assert.equal(densityLimitEvidence(bundle(layer(0, [texture(1.5)], {matrix: matrix(1.3)})), 0, 2).enlarged, false);
const fallback = texture();
delete fallback.rasterScale;
assert.equal(densityLimitEvidence(bundle(layer(0, [fallback], {matrix: matrix(1.3)})), 0, 2).enlarged, true);
const composite = bundle(layer(0, [texture(1.5)], {matrix: matrix(1.3), opacity: 0.5}));
assert.equal(densityLimitEvidence(composite, 0, 2).enlarged, true);
assert.equal(densityLimitEvidence(bundle(layer(0, [texture()], {matrix: matrix(1.3), opacity: 0.5, rasterScale: 1.5})), 0, 2).enlarged, true);
assert.equal(densityLimitEvidence(bundle(layer(0, [texture()], {matrix: matrix(1)})), 0, 2).enlarged, false);

const group = (extra = {}) => ({区域: '全图', 线: '运动', 指标: {ssim: 0.971, 大差比例_不算边: 0.001, 最大差异块: 0, 平均偏色: 0}, 阈值: {ssim: 0.975, 大差比例_不算边: 0.01, 最大差异块: 128, 平均偏色: 1.5}, 通过: false, 未通过: ['ssim'], ...extra});
const row = {路径: '新画法/ui_heart/gain/279.0587@2x.png', 通过: false, 运动基准: {ssim: 0.98}, 分组: [group()]};
assert.equal(isDensityLimit(row, evidence), true);
assert.equal(isDensityLimit({...row, 路径: '新画法/ui_heart/gain/350@2x.png'}, evidence), true);
assert.equal(isDensityLimit({...row, 路径: '新画法/ui_heart/gain/300@2x.png'}, evidence), false);
assert.equal(isDensityLimit({...row, 路径: '新画法/other/gain/350@2x.png'}, evidence), false);
assert.equal(isDensityLimit({...row, 通过: true}, evidence), false);
assert.equal(isDensityLimit({...row, 错误: '尺寸不同'}, evidence), false);
assert.equal(isDensityLimit({...row, 运动基准: undefined}, evidence), false);
assert.equal(isDensityLimit(row, {enlarged: false, layers: []}), false);
assert.equal(isDensityLimit({...row, 分组: [group({未通过: ['ssim', '最大差异块']})]}, evidence), false);
assert.equal(isDensityLimit({...row, 分组: [group({指标: {...group().指标, ssim: 0.94}})]}, evidence), false);
assert.equal(isDensityLimit({...row, 分组: [group(), group({区域: '非文字', 通过: true, 未通过: []}), group({区域: '文字', 线: '文字', 通过: true, 未通过: []})]}, evidence), false);
console.log('2 倍上限：不等间距、完整D、可见输出、实际密度和 SSIM 单项分类通过');
